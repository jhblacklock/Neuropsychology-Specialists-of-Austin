// Pure function: redirects.json + templates in, { relative path: contents } out.
// No imports, so generate.mjs and any other runner can share it.
export function build(config, templates) {
  const files = {};
  const rules = config.groups.flatMap(g => g.rules);
  const bare = p => p.replace(/^\//, '').replace(/\/$/, '');
  const esc = s => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
  const pattern = from => from.endsWith('/') ? `^${esc(bare(from))}/?$` : `^${esc(bare(from))}$`;
  // NE stops Apache escaping the "#" of a fragment destination to %23.
  const flags = to => `[R=301,${to.includes('#') ? 'NE,' : ''}L]`;
  const noSlash = p => p.endsWith('/') ? p.slice(0, -1) : p;
  const dated = { apache: '^20[0-9]{2}/[0-9]{2}/.+$', netlify: '/:year/:month/*', vercel: '/:year(20\\d{2})/:month(\\d{2})/:path*' };

  // .htaccess
  const ht = [templates.htaccessHead.trimEnd()];
  for (const g of config.groups) {
    ht.push('', `# ${g.name}`);
    for (const r of g.rules) {
      if (r.why) ht.push(`# ${r.why}`);
      ht.push(`RewriteRule ${pattern(r.from)} ${r.to} ${flags(r.to)}`);
    }
  }
  ht.push('', '# Feeds and the old Yoast sitemaps');
  for (const r of config.feeds) ht.push(`RewriteRule ${pattern(r.from)} ${r.to} ${flags(r.to)}`);
  ht.push('', '# Anything else under the retired plugin trees, or any other dated permalink from the old blog');
  for (const w of config.wildcards) {
    ht.push(`RewriteRule ${w.dated ? dated.apache : `^${esc(bare(w.tree))}/.+$`} ${w.to} ${flags(w.to)}`);
  }
  ht.push('', templates.htaccessTail.trim(), '');
  files['.htaccess'] = ht.join('\n');

  // _redirects (Netlify). Comments go on their own lines. "301!" forces the
  // rule over the stub file at the same path: without it Netlify serves the
  // stub, and the visitor gets a meta refresh instead of a 301.
  const pad = (s, n) => s + ' '.repeat(Math.max(2, n - s.length));
  const nl = ['# Netlify redirects. GENERATED by tools/redirects/generate.mjs from',
    '# tools/redirects/redirects.json; edit those, not this file. First match wins.'];
  const line = (from, to, status) => `${pad(from, 66)}${pad(to, 34)}${status}`;
  for (const g of config.groups) {
    nl.push('', `# ${g.name}`);
    for (const r of g.rules) {
      if (r.why) nl.push(`# ${r.why}`);
      nl.push(line(noSlash(r.from), r.to, r.stub ? '301!' : '301'));
    }
  }
  nl.push('', '# Feeds and the old Yoast sitemaps');
  for (const r of config.feeds) nl.push(line(noSlash(r.from), r.to, '301'));
  nl.push('', '# Anything else under the retired plugin trees or the old blog');
  for (const w of config.wildcards) nl.push(line(w.dated ? dated.netlify : `${noSlash(w.tree)}/*`, w.to, '301'));
  files['_redirects'] = nl.join('\n') + '\n';

  // vercel.json. Vercel applies redirects before the filesystem, so stubs never shadow them.
  const vr = [];
  for (const r of [...rules, ...config.feeds]) vr.push({ source: noSlash(r.from), destination: r.to, permanent: true });
  for (const w of config.wildcards) vr.push({ source: w.dated ? dated.vercel : `${noSlash(w.tree)}/:path*`, destination: w.to, permanent: true });
  files['vercel.json'] = JSON.stringify({ $schema: 'https://openapi.vercel.sh/vercel.json', cleanUrls: true, trailingSlash: true, redirects: vr }, null, 2) + '\n';

  // HTML stubs: the fallback for a host that cannot issue a 301 (GitHub Pages).
  for (const r of rules) {
    if (!r.stub) continue;
    const canonical = 'https://neuroaustin.com' + r.to.split('#')[0];
    files[`${bare(r.from)}/index.html`] = `<!DOCTYPE html>
<!-- MOVED-STUB -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Moved — Neuropsychology Specialists of Austin</title>
<link rel="canonical" href="${canonical}">
<meta http-equiv="refresh" content="0; url=${r.to}">
<script>window.location.replace("${r.to}");</script>
<style>
body{margin:0;background:#FFFFFF;color:#1F2D3D;font:400 17px/1.65 system-ui,-apple-system,'Segoe UI',sans-serif;padding:64px 24px}
a{color:#1F2D3D;border-bottom:1px solid #C28A33;text-decoration:none}
</style>
</head>
<body>
<!-- Client-side fallback only, for a host that cannot issue a 301. The
     server-side rules in .htaccess / _redirects / vercel.json take precedence
     and mean this file is never served. GENERATED: see tools/redirects/. -->
<p>This page has moved to <a href="${r.to}">${r.to}</a>.</p>
</body>
</html>
`;
  }
  return files;
}
